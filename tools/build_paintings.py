"""Build every painting from the photos in assets/.

    python tools/build_paintings.py

For each photo in assets/ it:
  1. reads its settings from assets/paintings.txt (or uses defaults)
  2. makes the textures in Content/Paintings/ (via make_painting.py)
  3. writes Content/PaintingList.cs, the list of paintings the mod loads
  4. writes the item names into Localization/

Run it again whenever you add, remove or change a photo.
"""

import re
import sys
from pathlib import Path

from make_painting import (DEFAULT_SIZE, OUT, ROOT, check_name, make_painting,
                           parse_focus, parse_size)

ASSETS = ROOT / "assets"
CONFIG = ASSETS / "paintings.txt"
PHOTO_TYPES = {".jpg", ".jpeg", ".png", ".webp", ".bmp"}

# Every recipe starts with this, at a Sawmill
BASE_RECIPE = [("Wood", 10)]
# Photos without a recipe in paintings.txt get the first ingredient here that
# no other painting uses yet, so every painting has its own recipe.
# Names are Terraria's ItemID names.
EXTRA_POOL = ["Amethyst", "Topaz", "Sapphire", "Emerald", "Ruby", "Diamond", "Amber",
              "Gel", "Lens", "Feather", "FallenStar", "Glass", "Daybloom", "Silk",
              "Cobweb", "Bone", "Acorn", "Mushroom", "Sunflower", "PinkGel"]


def camel_name(stem):
    """'juan-peron 2' -> 'JuanPeron2' (a valid C# class name)."""
    words = re.findall(r"[A-Za-z0-9]+", stem)
    name = "".join(w[:1].upper() + w[1:] for w in words)
    return name if name[:1].isalpha() else "Painting" + name


def parse_recipe(text):
    """'Wood 10, Ruby 1' -> [('Wood', 10), ('Ruby', 1)]"""
    recipe = []
    for part in text.split(","):
        match = re.fullmatch(r"\s*([A-Za-z]+)\s+(\d+)\s*", part)
        if not match:
            raise ValueError(f"recipe parts look like 'Ruby 1', got {part.strip()!r}")
        recipe.append((match[1], int(match[2])))
    return recipe


def read_config():
    """assets/paintings.txt -> {photo file name: settings}"""
    settings = {}
    if not CONFIG.exists():
        return settings
    for number, line in enumerate(CONFIG.read_text(encoding="utf-8").splitlines(), 1):
        line = line.split("#", 1)[0].strip()   # drop comments
        if not line:
            continue
        cols = [c.strip() for c in line.split("|")]
        cols += [""] * (6 - len(cols))
        photo, name, display, focus, size, recipe = cols[:6]
        try:
            entry = {
                "name": name or camel_name(Path(photo).stem),
                "display": display or None,
                "focus": parse_focus(focus) if focus and focus != "-" else None,
                "size": parse_size(size) if size and size != "-" else DEFAULT_SIZE,
                "recipe": parse_recipe(recipe) if recipe and recipe != "-" else None,
            }
            check_name(entry["name"])
        except ValueError as err:
            sys.exit(f"paintings.txt line {number}: {err}")
        settings[photo] = entry
    return settings


def cs_string(text):
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def write_painting_list(paintings):
    lines = [
        "// GENERATED by tools/build_paintings.py from assets/. Don't edit by hand:",
        "// change assets/paintings.txt and run the script again.",
        "namespace PresidentesArgentinos.Content",
        "{",
        "\tpublic static class PaintingList",
        "\t{",
        "\t\tpublic static readonly PaintingInfo[] All = {",
    ]
    for p in paintings:
        recipe = ", ".join(f"({cs_string(item)}, {count})" for item, count in p["recipe"])
        lines.append(f"\t\t\tnew({cs_string(p['name'])}, {p['size'][0]}, {p['size'][1]}, new[] {{ {recipe} }}),")
    lines += ["\t\t};", "\t}", "}", ""]
    (ROOT / "Content" / "PaintingList.cs").write_text("\n".join(lines), encoding="utf-8")


def write_localization(paintings):
    # Same names in English and Spanish; Terraria shows the one for its language
    texts = {
        "en-US": ("Portrait of {}", "A painting of {}"),
        "es-ES": ("Retrato de {}", "Una pintura de {}"),
    }
    folder = ROOT / "Localization"
    folder.mkdir(exist_ok=True)
    for lang, (title, tooltip) in texts.items():
        lines = ["# GENERATED by tools/build_paintings.py", "Items: {"]
        for p in paintings:
            lines += [
                f"\t{p['name']}: {{",
                f"\t\tDisplayName: {title.format(p['display'])}",
                f"\t\tTooltip: {tooltip.format(p['display'])}",
                "\t}",
            ]
        lines += ["}", ""]
        (folder / f"{lang}_Mods.PresidentesArgentinos.hjson").write_text("\n".join(lines), encoding="utf-8")


def main():
    settings = read_config()
    photos = sorted(p for p in ASSETS.iterdir() if p.suffix.lower() in PHOTO_TYPES)
    if not photos:
        sys.exit(f"No photos in {ASSETS}")

    # Remove old textures, so deleted photos don't leave paintings behind
    for old in OUT.glob("*.png"):
        old.unlink()

    paintings, used = [], set()
    for photo in photos:
        entry = settings.get(photo.name)
        if entry is None:
            entry = {"name": camel_name(photo.stem), "display": None, "focus": None,
                     "size": DEFAULT_SIZE, "recipe": None}
            print(f"  note: {photo.name} has no line in paintings.txt, using defaults")
        entry["display"] = entry["display"] or entry["name"]
        paintings.append(entry)
        if entry["recipe"]:
            used.update(item for item, _ in entry["recipe"])

    # Give each painting without a recipe its own extra ingredient
    for p in paintings:
        if p["recipe"] is None:
            extra = next(i for i in EXTRA_POOL if i not in used)
            used.add(extra)
            p["recipe"] = BASE_RECIPE + [(extra, 1)]

    names = [p["name"] for p in paintings]
    if len(set(names)) != len(names):
        sys.exit(f"Two paintings have the same name: {names}")
    recipes = [tuple(sorted(p["recipe"])) for p in paintings]
    if len(set(recipes)) != len(recipes):
        sys.exit("Two paintings have the same recipe; every painting needs its own")

    for photo, p in zip(photos, paintings):
        make_painting(photo, p["name"], p["size"], p["focus"])
        recipe = " + ".join(f"{n} {i}" for i, n in p["recipe"])
        print(f"{p['name']:<22} {p['size'][0]}x{p['size'][1]}  {recipe}")

    write_painting_list(paintings)
    write_localization(paintings)
    print(f"\n{len(paintings)} paintings built. Previews: tools/previews/")


if __name__ == "__main__":
    main()
